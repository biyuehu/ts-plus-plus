/**
 * Generates src/examples.js from the monorepo's packages/examples/ directory: for each example
 * project, reads its tsppconfig.json feature list (normalizing a bare string to an array),
 * its entry source (index.tspp, or the first .tspp in src/), and — for multi-file projects —
 * every .tspp file so the playground can offer per-file tabs.
 *
 * Run from the playground package; TSPP_REPO may override the monorepo root.
 */
import { readFileSync, existsSync, readdirSync, writeFileSync, mkdirSync } from "node:fs";
import { join, dirname } from "node:path";
import { fileURLToPath } from "node:url";

const root = dirname(dirname(fileURLToPath(import.meta.url)));
const mainRepo = process.env.TSPP_REPO ?? join(root, "..", "..");
const examplesDir = join(mainRepo, "packages", "examples");
if (!existsSync(examplesDir)) {
  console.error(`packages/examples/ not found under ${mainRepo}`);
  process.exit(1);
}

const examples = [];
for (const name of readdirSync(examplesDir, { withFileTypes: true })) {
  if (!name.isDirectory() || !/^\d{2}-/.test(name.name)) continue;
  const dir = join(examplesDir, name.name);

  let features = [];
  const configPath = join(dir, "tsppconfig.json");
  if (existsSync(configPath)) {
    // tsppconfig.json contains comments; strip // lines before JSON.parse
    const raw = readFileSync(configPath, "utf8").replace(/^\s*\/\/.*$/gm, "");
    const parsed = JSON.parse(raw);
    const list = parsed.compilerOptions?.tsppFeatures ?? [];
    features = Array.isArray(list) ? list : [list];
  }

  // All .tspp sources of the project, in a stable order: a root index.tspp first,
  // then src/*.tspp alphabetically (each file is a self-contained chapter).
  const files = [];
  if (existsSync(join(dir, "index.tspp"))) {
    files.push({ name: "index.tspp", path: join(dir, "index.tspp") });
  }
  const src = join(dir, "src");
  if (existsSync(src)) {
    for (const f of readdirSync(src).filter(f => f.endsWith(".tspp")).sort()) {
      files.push({ name: f, path: join(src, f) });
    }
  }
  if (!files.length) continue;
  const entryFile = files[0].path;
  const code = readFileSync(entryFile, "utf8");

  const id = name.name.replace(/^\d{2}-/, "");
  const title = id.split("-").map(w => w[0].toUpperCase() + w.slice(1)).join(" ");
  examples.push({
    id,
    title,
    features,
    code,
    // The entry is also exposed as `code`; only ship the file list when the project
    // actually spans several files, so single-file examples keep their old shape.
    ...(files.length > 1
      ? { files: files.map(f => ({ name: f.name, code: readFileSync(f.path, "utf8") })) }
      : {}),
  });
}

const output = `// Generated by scripts/generate-examples.mjs from ${
  process.env.TSPP_REPO ?? "../.."
}/packages/examples — do not edit by hand.
export const examples = ${JSON.stringify(examples, null, 2)};
`;
writeFileSync(join(root, "src", "examples.js"), output);

// Also emit the official playground example shape (public/js/examples/<lang>.json TOC
// + code files) so vendor getExampleSourceCode can load them on the deployed site.
const publicDir = join(root, "public", "js", "examples");
mkdirSync(publicDir, { recursive: true });
writeFileSync(
  join(publicDir, "en.json"),
  JSON.stringify(
    {
      examples: examples.map(e => ({
        id: e.id,
        title: e.title,
        // "." keeps the official loader URL (/js/examples/./<id>.tspp) pointed at the
        // flat files this generator writes next to the TOC
        lang: ".",
        name: `${e.id}.tspp`,
        path: [],
        hash: "",
      })),
    },
    null,
    2,
  ),
);
for (const e of examples) {
  writeFileSync(join(publicDir, `${e.id}.tspp`), e.code);
}
console.log(`Generated ${examples.length} examples -> src/examples.js + public/js/examples/`);
examples.forEach(e => console.log(`  ${e.id}  features=[${e.features.join(", ")}]  ${Math.round(e.code.length / 102.4) / 10}KB`));
